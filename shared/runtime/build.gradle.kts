            else binaryOption("sourceInfoType", "libbacktrace")
            if (appleSlice == null || appleSlice == target.name) xcFramework.add(this)
        }
    }
    sourceSets {
        val debugSources = listOf(file("src/debugMain/kotlin"), demoFrames)
        jvmTest { kotlin.srcDirs(debugSources) }
        jsTest { kotlin.srcDirs(debugSources) }
        macosMain { kotlin.srcDirs(debugSources) }
        if (devTools) iosMain { kotlin.srcDirs(debugSources) }
        matching { it.name == "androidDebug" }.configureEach { kotlin.srcDirs(debugSources) }
        commonMain { kotlin.srcDir(rootDir.resolve("generated/kotlin")) }
        commonMain.dependencies {
            api(project(":application"))
            api(project(":kit"))
            implementation(project(":data"))
            implementation(libs.kotlinx.serialization.json)
        }
        commonTest.dependencies { implementation(libs.kotlinx.coroutines.test) }
        androidMain.dependencies { implementation(libs.kotlinx.coroutines.android) }
        androidUnitTest.dependencies {
            implementation(libs.robolectric)
            implementation(libs.junit)
        }
        jvmTest.dependencies { implementation(libs.konsist) }
    }
}

