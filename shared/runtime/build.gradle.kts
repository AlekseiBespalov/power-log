val demoFrames =
    tasks.register("generateDemoFrames") {
        val fixtures = rootDir.parentFile.resolve("tests/fixtures")
        val identity = fixtures.resolve("contract/telemetry/cyc/identity.json")
        val protocol = fixtures.resolve("protocol.json")
        val output = layout.buildDirectory.dir("generated/demo-frames")
        inputs.files(identity, protocol).withPropertyName("fixtures").withPathSensitivity(PathSensitivity.RELATIVE)
        outputs.dir(output)
        doLast {
            fun crc(payload: List<Int>): Int {
                var crc = 0
                for (byte in payload) {
                    crc = crc xor (byte shl 8)
                    repeat(8) { crc = ((crc shl 1) xor if (crc and 0x8000 != 0) 0x1021 else 0) and 0xffff }
                }
                return crc
            }
            fun frame(payloadHex: String): String {
                val payload = payloadHex.chunked(2).map { it.toInt(16) }
                require(payload.size in 1..255) { "a demo reply frame needs a short header" }
                val check = crc(payload)
                return "02%02x%s%02x%02x03".format(payload.size, payloadHex, check shr 8, check and 0xff)
            }
            val cases = (JsonSlurper().parse(identity) as Map<*, *>)["cases"] as List<*>
            val first = cases.first() as Map<*, *>
            require(first["valid"] == true) { "the first identity case is a valid identity" }
            val vectors = JsonSlurper().parse(protocol) as Map<*, *>
            val requests = vectors["requests"] as Map<*, *>
            val recorded =
                (vectors["telemetry"] as List<*>)
                    .map { it as Map<*, *> }
                    .filter { (it["name"] as String).startsWith("live-") }
                    .map { frame(it["payloadHex"] as String) }
            require(recorded.isNotEmpty()) { "protocol.json holds recorded live telemetry" }
            val source = buildString {
                appendLine("// Generated by :runtime:generateDemoFrames from tests/fixtures; do not edit.")
                appendLine("package app.powerlog.runtime.dev")
                appendLine()
                appendLine("internal object DemoFrames {")
                appendLine("    val identityRequest: ByteArray = bytes(\"${requests["identity"]}\")")
                appendLine("    val telemetryRequest: ByteArray = bytes(\"${requests["selective"]}\")")
                appendLine("    val identity: ByteArray = bytes(\"${frame(first["payloadHex"] as String)}\")")
                appendLine("    val telemetry: List<ByteArray> =")
                appendLine("        listOf(${recorded.joinToString(", ") { "bytes(\"$it\")" }})")
                appendLine()
                appendLine("    private fun bytes(hex: String): ByteArray =")
                appendLine("        ByteArray(hex.length / 2) { hex.substring(it * 2, it * 2 + 2).toInt(16).toByte() }")
                appendLine("}")
            }
            output.get().file("app/powerlog/runtime/dev/DemoFrames.kt").asFile.apply {
                parentFile.mkdirs()
                writeText(source)
            }
        }
    }

kotlin {
