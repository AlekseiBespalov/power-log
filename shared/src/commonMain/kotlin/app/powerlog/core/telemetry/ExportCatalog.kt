package app.powerlog.core.telemetry

class ExportColumnDeclaration
private constructor(
    val name: String,
    val type: String,
    val platforms: List<String>,
    val consumers: List<String>,
) {
    constructor(
        key: ExportNumericKey,
        platforms: List<String>,
        consumers: List<String>,
    ) : this(key.name, "number", platforms, consumers)

    constructor(
        key: ExportStringKey,
        platforms: List<String>,
        consumers: List<String>,
    ) : this(key.name, "string", platforms, consumers)
}

data class ExportProjectionDeclaration(
    val name: String,
    val kinds: List<String>,
    val columns: List<ExportColumnDeclaration>,
) {
    fun columnsFor(platform: String, kind: String): List<ExportColumnDeclaration> = columns.filter {
        platform in it.platforms && (kind in it.consumers || (kind == "fit" && "discovery" in it.consumers))
    }
}

data class ExportFieldDeclaration(
    val name: String,
    val type: String,
    val description: String,
    val reads: List<String>,
    val unit: String? = null,
    val vendor: String? = null,
)

data class ExportTableDeclaration(
    val name: String,
    val path: String,
    val projection: String,
    val fields: List<ExportFieldDeclaration>,
)

