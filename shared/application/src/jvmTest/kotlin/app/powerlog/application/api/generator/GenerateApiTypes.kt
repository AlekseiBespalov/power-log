private const val HEADER = "// Generated by `npm run build:generated`; do not edit."

private const val EXPORT_PAGE = "exports.page"

private const val LINE_WIDTH = 120

private val anyMembers = setOf("equals", "hashCode", "toString")

private val identifier = Regex("[A-Za-z_$][A-Za-z0-9_$]*")

public fun main(args: Array<String>) {
    val output = File(args.first())
    output.deleteRecursively()
    val root = args.getOrNull(1)?.let { Class.forName(it).kotlin } ?: PowerLogApi::class
    val surface = surface(root, section = args.getOrNull(2))
    val api = typeScript(surface)
    val section = surface.section
    if (section == null) {
        output.write("ts/api.ts", api.text)
        output.write("ts/export-tables.ts", exportTables())
        output.write("kotlin/app/powerlog/runtime/ApiHash.kt", apiHash(api.hash))
        output.write("kotlin/app/powerlog/runtime/bridge/ApiDispatch.kt", apiDispatch(surface, "ApiDispatch"))
    } else {
        val dispatch = "${section.replaceFirstChar(Char::uppercaseChar)}Dispatch"
        output.write("ts/$section.ts", api.text)
        output.write("kotlin/app/powerlog/runtime/bridge/$dispatch.kt", apiDispatch(surface, dispatch))
    }
}

private sealed interface Member

private class Operation(val name: String, val input: KType, val output: KType) : Member

private class Stream(val name: String, val params: KType, val value: KType) : Member

private class Surface(
    val root: KClass<*>,
    val section: String?,
    val names: Set<String>,
    val calls: List<Operation>,
    val streams: List<Stream>,
    val exportPage: Operation?,
)

private class GeneratedApi(val text: String, val hash: String)

private fun surface(root: KClass<*>, section: String?): Surface {
    val prefix = section?.let { "$it." }.orEmpty()
    val groups = root.memberProperties
    val functions = root.memberFunctions.filter { it.name !in anyMembers }
    val grouped = groups.flatMap { group ->
        val type = group.returnType.classifier as? KClass<*> ?: error("${root.simpleName}.${group.name} is not a group")
        type.members.mapNotNull { member(it, "$prefix${group.name}.${it.name}", streams = true) }
    }
    val members = grouped + functions.mapNotNull { member(it, "$prefix${it.name}", streams = false) }
    val operations = members.filterIsInstance<Operation>()
    val exportPage =
        if (section != null) null
        else operations.find { it.name == EXPORT_PAGE } ?: error("${root.simpleName} has no $EXPORT_PAGE")
    val apiVersion = Operation("apiVersion", typeOf<Empty>(), typeOf<ApiVersion>()).takeIf { section == null }
    return Surface(
        root = root,
        section = section,
        names = section?.let(::setOf) ?: (groups.map { it.name } + functions.map { it.name }).toSortedSet(),
        calls = (operations - listOfNotNull(exportPage) + listOfNotNull(apiVersion)).sortedBy { it.name },
        streams = members.filterIsInstance<Stream>().sortedBy { it.name },
        exportPage = exportPage,
    )
}

private fun member(member: KCallable<*>, name: String, streams: Boolean): Member? =
    when {
        member is KFunction<*> && member.isSuspend -> operation(name, member)
        streams && member is KProperty1<*, *> && member.returnType.classifier == ApiStream::class ->
            Stream(name, argument(member.returnType, 0), argument(member.returnType, 1))
        member is KFunction<*> && member.name in anyMembers -> null
        else -> error("$name is neither a suspend operation nor an ApiStream")
    }

private fun operation(name: String, function: KFunction<*>): Operation {
    val input = function.valueParameters.singleOrNull()?.type ?: error("$name does not take exactly one input")
    if (function.returnType.classifier != Outcome::class) error("$name answers ${function.returnType}, not an Outcome")
    return Operation(name, input, argument(function.returnType, 0))
}

private fun argument(type: KType, index: Int): KType =
    type.arguments[index].type ?: error("$type has a star projection")

private fun typeScript(surface: Surface): GeneratedApi {
    val types = TypeScriptTypes()
    val failureCode = if (surface.section == null) types.reference(typeOf<FailureCode>()) else null
    val calls =
        surface.calls.map { call ->
            "${key(call.name)}: { input: ${types.reference(call.input)}; output: ${types.output(call.output)} };"
        }
    val streams =
        surface.streams.map { stream ->
            "${key(stream.name)}: { params: ${types.reference(stream.params)}; value: ${types.reference(stream.value)} };"
        }
    val exportPage =
        surface.exportPage?.let { page ->
            block(
                "export interface ExportPageCall",
                listOf("input: ${types.reference(page.input)};", "output: ${types.reference(page.output)};"),
            )
        }
    val queries = surface.calls.filter { it.name != "cancel" && takesKey(it.input) }.map { quote(it.name) }
    val sections =
        types.declarations.filterKeys { it != failureCode }.values +
            listOfNotNull(
                block("export interface Calls", calls),
                block("export interface Streams", streams),
                exportPage,
                if (queries.isEmpty()) "export type QueryName = never;" else alias("QueryName", queries),
                failureCode?.let(types.declarations::getValue),
            )
    val text = sections.joinToString("\n\n", prefix = "$HEADER\n\n", postfix = "\n\n")
    val hash = sha256(text).take(16)
    val constant = surface.section?.let { "${it.uppercase()}_HASH" } ?: "API_HASH"
    return GeneratedApi("${text}export const $constant = '$hash';\n", hash)
}

internal class TypeScriptTypes {
    val declarations: MutableMap<String, String> = sortedMapOf()

    private val claims = mutableMapOf<String, Pair<KClass<*>, String?>>()

    fun output(type: KType): String = if (type.isUnit()) "null" else reference(type)

    fun reference(type: KType): String {
        if (type.isMarkedNullable) return "${reference(type.withNullability(false))} | null"
        val kClass = type.classifier as? KClass<*> ?: error("$type is not a class")
        when (kClass) {
            Unit::class -> error("Unit is only an operation's output")
            ByteArray::class -> error("No DTO carries a ByteArray")
            ExportColumn::class -> error("ExportColumn crosses only as the values of ExportPage.columns")
        }
        val descriptor = descriptorOf(type)
        if (descriptor.serialName.startsWith("kotlinx.serialization.json."))
            error("No DTO carries a JSON element: $type")
        return when (val kind = descriptor.kind) {
            is PrimitiveKind -> primitive(kind)
            SerialKind.ENUM -> enumeration(kClass, descriptor)
            StructureKind.LIST -> list(type, descriptor)
            StructureKind.MAP -> map(type, descriptor)
            StructureKind.CLASS ->
                if (descriptor.isInline) reference(underlying(kClass)) else record(kClass, descriptor, null)
            StructureKind.OBJECT -> record(kClass, descriptor, null)
            PolymorphicKind.SEALED -> union(kClass, descriptor)
            else -> error("${descriptor.serialName} has the unsupported descriptor kind $kind")
        }
    }

    private fun enumeration(kClass: KClass<*>, descriptor: SerialDescriptor): String =
        declare(nameOf(kClass), kClass, null) { name ->
            alias(name, (0 until descriptor.elementsCount).map { quote(descriptor.getElementName(it)) })
        }

    private fun list(type: KType, descriptor: SerialDescriptor): String {
        val element = type.arguments.singleOrNull()?.type
        val item = if (element != null) reference(element) else primitive(descriptor.getElementDescriptor(0).kind)
        return if (" | " in item) "($item)[]" else "$item[]"
    }

    private fun map(type: KType, descriptor: SerialDescriptor): String {
        val key = descriptor.getElementDescriptor(0)
        val keyType =
            when {
                key.isNullable -> error("$type has a nullable key")
                key.kind == PrimitiveKind.STRING -> "string"
                key.kind == SerialKind.ENUM -> reference(argument(type, 0))
                else -> error("$type is keyed by neither strings nor enums")
            }
        return "Record<$keyType, ${reference(argument(type, 1))}>"
    }

    private fun record(kClass: KClass<*>, descriptor: SerialDescriptor, kind: String?): String =
        declare(nameOf(kClass), kClass, kind) { name ->
            val properties = kClass.memberProperties.associateBy { it.findAnnotation<SerialName>()?.value ?: it.name }
            val fields =
                (0 until descriptor.elementsCount).map { index ->
                    val element = descriptor.getElementName(index)
                    val property = properties[element] ?: error("$name.$element is not a property")
                    val type =
                        if (kClass == ExportPage::class && element == "columns") exportColumns(property.returnType)
                        else reference(property.returnType)
                    "${key(element)}: $type;"
                }
            val all = listOfNotNull(kind?.let { "kind: ${quote(it)};" }) + fields
            if (all.isEmpty()) "export type $name = Record<string, never>;" else block("export interface $name", all)
        }

    private fun union(kClass: KClass<*>, descriptor: SerialDescriptor): String =
        declare(nameOf(kClass), kClass, null) { name ->
            val leaves = leavesOf(kClass).associateBy { descriptorOf(it.starProjectedType).serialName }
            val subclasses = descriptor.getElementDescriptor(1)
            val members =
                (0 until subclasses.elementsCount).map { index ->
                    val serialName = subclasses.getElementName(index)
                    val leaf = leaves[serialName] ?: error("$name has no subclass serialized as $serialName")
                    if (serialName == leaf.qualifiedName) error("${leaf.qualifiedName} has no @SerialName")
                    record(leaf, subclasses.getElementDescriptor(index), serialName)
                }
            alias(name, members)
        }

    private fun exportColumns(type: KType): String {
        if (type != typeOf<Map<String, ExportColumn>>())
            error("ExportPage.columns is $type, not Map<String, ExportColumn>")
        declare("ExportColumn", ExportColumn::class, null) {
            "export type ExportColumn = Uint8Array | (string | null)[];"
        }
        return "Record<string, ExportColumn>"
    }

    private fun declare(name: String, kClass: KClass<*>, kind: String?, text: (String) -> String): String {
        val claim = kClass to kind
        val existing = claims.putIfAbsent(name, claim)
        when {
            existing == null -> declarations[name] = text(name)
            existing.first != kClass ->
                error("Two types are named $name: ${existing.first.qualifiedName} and ${kClass.qualifiedName}")
            existing.second != kind -> error("${kClass.qualifiedName} is used both inside and outside its sealed union")
        }
        return name
    }
}

private fun primitive(kind: SerialKind): String =
    when (kind) {
        PrimitiveKind.STRING,
        PrimitiveKind.CHAR -> "string"
        PrimitiveKind.BOOLEAN -> "boolean"
        is PrimitiveKind -> "number"
        else -> error("$kind is not a primitive kind")
    }

private fun takesKey(type: KType): Boolean {
    val descriptor = descriptorOf(type)
    val index = descriptor.getElementIndex("key")
    if (index == CompositeDecoder.UNKNOWN_NAME) return false
    val key = descriptor.getElementDescriptor(index)
    return key.kind == PrimitiveKind.STRING && !key.isNullable
}

private fun descriptorOf(type: KType): SerialDescriptor {
    val serializer = runCatching { serializer(type) }.getOrElse { error("$type has no serializer: ${it.message}") }
    return serializer.descriptor
}

private fun underlying(kClass: KClass<*>): KType =
    kClass.primaryConstructor?.parameters?.singleOrNull()?.type
        ?: error("${kClass.qualifiedName} does not wrap exactly one value")

private fun leavesOf(kClass: KClass<*>): List<KClass<*>> =
    kClass.sealedSubclasses.flatMap { if (it.isSealed) leavesOf(it) else listOf(it) }

private fun nameOf(kClass: KClass<*>): String {
    val simple = kClass.simpleName ?: error("$kClass has no simple name")
    val outer = kClass.java.declaringClass?.kotlin ?: return simple
    return if (kClass.isSubclassOf(outer)) nameOf(outer) + simple else simple
}

private fun KType.isUnit(): Boolean = classifier == Unit::class && !isMarkedNullable

private fun alias(name: String, members: List<String>): String {
    val union = "${members.joinToString(" | ")};"
    return when {
        "export type $name = $union".length <= LINE_WIDTH -> "export type $name = $union"
        "  $union".length <= LINE_WIDTH -> "export type $name =\n  $union"
        else -> "export type $name =\n${members.joinToString("\n") { "  | $it" }};"
    }
}

private fun block(head: String, lines: List<String>): String = "$head {\n${lines.joinToString("\n") { "  $it" }}\n}"

private fun key(name: String): String = if (identifier.matches(name)) name else quote(name)

private fun quote(text: String): String = "'${text.replace("\\", "\\\\").replace("'", "\\'")}'"

private fun sha256(text: String): String =
    MessageDigest.getInstance("SHA-256").digest(text.toByteArray(Charsets.UTF_8)).joinToString("") {
        "%02x".format(it)
    }

private fun apiHash(hash: String): String =
    "$HEADER\npackage app.powerlog.runtime\n\ninternal const val API_HASH: String = \"$hash\"\n"

private fun apiDispatch(surface: Surface, className: String): String {
    val imports = sortedSetOf(surface.root.qualifiedName!!, "kotlinx.serialization.json.JsonObject")
    fun serializer(type: KType): String {
        val kClass = type.classifier as? KClass<*>
        if (kClass == null || type.isMarkedNullable || type.arguments.isNotEmpty())
            error("$type is not a named @Serializable type")
        val packageName = kClass.java.packageName
        val name = kClass.qualifiedName!!.removePrefix("$packageName.")
        imports += "$packageName.${name.substringBefore('.')}"
        return "$name.serializer()"
    }
    fun member(name: String): String = name.removePrefix(surface.section?.let { "$it." }.orEmpty())
    val calls =
        surface.calls
            .filter { it.name != "apiVersion" }
            .map { operation ->
                val call = "api.${member(operation.name)}(codec.decode(${serializer(operation.input)}, input))"
                branch(
                    operation.name,
                    if (operation.output.isUnit()) "codec.answerUnit($call)"
                    else "codec.answer(${serializer(operation.output)}, $call)",
                )
            }
    val streams =
        surface.streams.map { stream ->
            val call = "api.${member(stream.name)}.next(codec.decode(${serializer(stream.params)}, params), after, key)"
            branch(stream.name, "codec.next(${serializer(stream.value)}, $call)")
        }
    val exportPage =
        surface.exportPage?.let { page ->
            if (page.output.classifier != ExportPage::class)
                error("$EXPORT_PAGE answers ${page.output}, not ExportPage")
            "codec.page(api.$EXPORT_PAGE(codec.decode(${serializer(page.input)}, input)))"
        }
    val api = surface.root.simpleName
    return buildString {
        appendLine(HEADER)
        appendLine("package app.powerlog.runtime.bridge")
        appendLine()
        imports.forEach { appendLine("import $it") }
        appendLine()
        appendLine("internal class $className(private val api: $api, private val codec: WireCodec) : ApiSection {")
        appendLine("    override val names: Set<String> =")
        appendLine("        setOf(")
        surface.names.forEach { appendLine("            \"$it\",") }
        appendLine("        )")
        appendLine()
        appendLine("    override suspend fun call(op: String, input: JsonObject): String? =")
        appendLine("        when (op) {")
        calls.forEach(::appendLine)
        appendLine("            else -> null")
        appendLine("        }")
        appendLine()
        appendLine(
            "    override suspend fun next(stream: String, params: JsonObject, after: Long?, key: String): String? ="
        )
        appendLine("        when (stream) {")
        streams.forEach(::appendLine)
        appendLine("            else -> null")
        appendLine("        }")
        if (exportPage != null) {
            appendLine()
            appendLine("    internal suspend fun exportPage(input: JsonObject): BinaryPage =")
            appendLine("        $exportPage")
        }
        appendLine("}")
    }
}

private fun branch(name: String, expression: String): String = "            \"$name\" ->\n                $expression"

private fun exportTables(): String = buildString {
    appendLine(HEADER)
    appendLine()
    appendLine("export const EXPORT_TABLES = [")
    for (table in ExportCatalog.tables) {
        appendLine("  {")
        appendLine("    name: ${quoted(table.name)},")
        appendLine("    path: ${quoted(table.path)},")
        appendLine("    projection: ${quoted(table.projection)},")
        appendLine("    fields: [")
        for (field in table.fields) {
            val parts =
                listOfNotNull(
                    "name: ${quoted(field.name)}",
                    "type: ${quoted(field.type)}",
                    "description: ${quoted(field.description)}",
                    "reads: [${field.reads.joinToString(", ", transform = ::quoted)}]",
                    field.unit?.let { "unit: ${quoted(it)}" },
                    field.vendor?.let { "vendor: ${quoted(it)}" },
                )
            appendLine("      { ${parts.joinToString(", ")} },")
        }
        appendLine("    ],")
        appendLine("  },")
    }
    appendLine("] as const;")
}

private fun quoted(text: String): String = "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"

private fun File.write(path: String, text: String) {
    val file = resolve(path)
    file.parentFile.mkdirs()
    file.writeText(text)
}
